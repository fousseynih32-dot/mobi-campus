// Langue courante : 'bi' (bilingue BM+FR), 'fr', 'bm', 'en'
window.currentLang = localStorage.getItem('mobi_lang') || 'bi';

window.setLang = function(lang) {
  window.currentLang = lang;
  localStorage.setItem('mobi_lang', lang);
  location.reload();
};

/**
 * Retourne le texte dans la langue active.
 * - 'bi' → bambara (par défaut, car bilingue met BM en avant)
 * - 'fr' → français
 * - 'bm' → bambara
 * - 'en' → anglais
 */
window.t = function(key) {
  const entry = I18N[key] || { fr: key, bm: key, en: key };
  if (window.currentLang === 'fr') return entry.fr;
  if (window.currentLang === 'en') return entry.en;
  if (window.currentLang === 'bm') return entry.bm;
  return entry.bm; // bilingue → BM en avant
};

/**
 * Retourne le HTML bilingue.
 * - 'bi' → BM en gras + FR en petit en dessous (ou à côté)
 * - 'fr' / 'bm' / 'en' → texte seul
 */
window.dual = function(frKey, opts = {}) {
  const entry = I18N[frKey] || { fr: frKey, bm: frKey, en: frKey };
  const { block = false, subtle = true } = opts;

  if (window.currentLang === 'fr') return entry.fr;
  if (window.currentLang === 'en') return entry.en;
  if (window.currentLang === 'bm') return entry.bm;

  // Bilingue : bambara en avant + français en dessous en petit gris
  if (block) {
    return `<span class="block">
      <span class="block font-bold">${entry.bm}</span>
      <span class="block text-[10px] text-gray-500 font-normal">${entry.fr}</span>
    </span>`;
  }
  return `<span class="font-bold">${entry.bm}</span> <span class="text-[10px] text-gray-500 font-normal">(${entry.fr})</span>`;
};

/**
 * Version message bilingue brut (pour toasts, alertes).
 */
window.toastDual = function(frKey) {
  const entry = I18N[frKey] || { fr: frKey, bm: frKey, en: frKey };
  if (window.currentLang === 'fr') return entry.fr;
  if (window.currentLang === 'en') return entry.en;
  if (window.currentLang === 'bm') return entry.bm;
  return `${entry.bm} · ${entry.fr}`;
};